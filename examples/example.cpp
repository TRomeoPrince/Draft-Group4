#include "Annotation.hpp"
#include "CountPlot.hpp"
#include "DataLoader.hpp"
#include "DataProcessor.hpp"
#include "Histogram.hpp"
#include "ImageExporter.hpp"
#include "KDEPlot.hpp"
#include "Renderer.hpp"
#include "Statistics.hpp"

#include <iostream>
#include <string>
#include <vector>

int main() {
    try {
        std::vector<double> marks{
            55, 60, 62, 65, 67, 70, 70, 72, 75, 80, 85, 90
        };

        std::vector<std::string> programmes{
            "CCE", "EEE", "CCE", "CIV", "CCE",
            "EEE", "CCE", "CIV", "CCE", "EEE"
        };

        std::cout << "Count: " << Statistics::count(marks) << "\n";
        std::cout << "Mean: " << Statistics::mean(marks) << "\n";
        std::cout << "Min: " << Statistics::minimum(marks) << "\n";
        std::cout << "Max: " << Statistics::maximum(marks) << "\n";

        auto counts = CountPlot::calculate(programmes);
        auto bins = Histogram::build(marks, 5);
        auto kde = KDEPlot::estimate(marks, 120);

        Annotation note;
        note.add(580, 80, "Generated by Group 4 library");

        std::string countSvg =
            Renderer::renderCountPlot(counts, 800, 500, "Programme Count", note);

        std::string histogramSvg =
            Renderer::renderHistogram(bins, 800, 500, "Marks Histogram", note);

        std::string kdeSvg =
            Renderer::renderKDE(kde, 800, 500, "Marks KDE", note);

        ImageExporter::saveSVG(countSvg, "count_plot.svg");
        ImageExporter::saveSVG(histogramSvg, "histogram.svg");
        ImageExporter::saveSVG(kdeSvg, "kde_plot.svg");

        std::cout << "Created count_plot.svg, histogram.svg and kde_plot.svg\n";

        // Optional CSV demonstration:
        // auto table = DataLoader::loadCSV("data/input/sample.csv");
        // auto cleaned = DataProcessor::cleanRows(table);
        // auto markText = DataProcessor::getColumn(cleaned, 2);
        // auto loadedMarks = DataProcessor::toNumeric(markText);

    } catch (const std::exception& error) {
        std::cerr << "Error: " << error.what() << "\n";
        return 1;
    }

    return 0;
}
